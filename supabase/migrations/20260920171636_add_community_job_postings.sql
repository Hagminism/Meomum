ALTER TABLE public.posts
  ADD COLUMN IF NOT EXISTS job_wage_type TEXT,
  ADD COLUMN IF NOT EXISTS job_wage_amount NUMERIC(14, 2),
  ADD COLUMN IF NOT EXISTS job_working_time TEXT,
  ADD COLUMN IF NOT EXISTS job_recruitment_deadline DATE,
  ADD COLUMN IF NOT EXISTS job_is_always_recruiting BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE public.posts
  DROP CONSTRAINT IF EXISTS posts_job_fields_check;

ALTER TABLE public.posts
  ADD CONSTRAINT posts_job_fields_check CHECK (
    category = 'job'
    OR (
      job_wage_type IS NULL
      AND job_wage_amount IS NULL
      AND job_working_time IS NULL
      AND job_recruitment_deadline IS NULL
      AND job_is_always_recruiting = FALSE
    )
  );

CREATE OR REPLACE FUNCTION public.clear_non_job_post_fields()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.category <> 'job' THEN
    NEW.job_wage_type := NULL;
    NEW.job_wage_amount := NULL;
    NEW.job_working_time := NULL;
    NEW.job_recruitment_deadline := NULL;
    NEW.job_is_always_recruiting := FALSE;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS clear_non_job_post_fields_trigger ON public.posts;
CREATE TRIGGER clear_non_job_post_fields_trigger
  BEFORE INSERT OR UPDATE OF category, job_wage_type, job_wage_amount,
    job_working_time, job_recruitment_deadline, job_is_always_recruiting
  ON public.posts
  FOR EACH ROW
  EXECUTE FUNCTION public.clear_non_job_post_fields();

