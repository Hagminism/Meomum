-- 클라이언트가 게시물 작성자 ID나 일자리 전용 컬럼을 직접 조작하지 않도록 서버 RPC로 저장합니다.
CREATE OR REPLACE FUNCTION public.create_job_post_with_images(
  p_upper_region TEXT,
  p_lower_region TEXT,
  p_title TEXT,
  p_content TEXT,
  p_images JSONB DEFAULT '[]'::JSONB,
  p_place_name TEXT DEFAULT NULL,
  p_place_latitude DOUBLE PRECISION DEFAULT NULL,
  p_place_longitude DOUBLE PRECISION DEFAULT NULL,
  p_place_address TEXT DEFAULT NULL,
  p_place_road_address TEXT DEFAULT NULL,
  p_place_category TEXT DEFAULT NULL,
  p_job_wage_type TEXT DEFAULT NULL,
  p_job_wage_amount NUMERIC DEFAULT NULL,
  p_job_working_time TEXT DEFAULT NULL,
  p_job_recruitment_deadline DATE DEFAULT NULL,
  p_job_is_always_recruiting BOOLEAN DEFAULT FALSE
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_account_id UUID := public.current_account_id();
  v_post_id UUID;
  v_image JSONB;
BEGIN
  IF v_account_id IS NULL THEN
    RAISE EXCEPTION 'Authenticated account is required';
  END IF;

  IF NULLIF(BTRIM(p_upper_region), '') IS NULL
    OR NULLIF(BTRIM(p_lower_region), '') IS NULL THEN
    RAISE EXCEPTION '게시 지역을 입력해주세요.';
  END IF;

  IF NULLIF(BTRIM(p_title), '') IS NULL THEN
    RAISE EXCEPTION '제목을 입력해주세요.';
  END IF;

  IF NULLIF(BTRIM(p_content), '') IS NULL THEN
    RAISE EXCEPTION '내용을 입력해주세요.';
  END IF;

  IF CHAR_LENGTH(BTRIM(p_title)) > 50 THEN
    RAISE EXCEPTION '제목은 50자 이내로 입력해주세요.';
  END IF;

  IF CHAR_LENGTH(BTRIM(p_content)) > 10000 THEN
    RAISE EXCEPTION '본문은 10,000자 이내로 입력해주세요.';
  END IF;

  IF p_job_wage_type IS NOT NULL
    AND p_job_wage_type NOT IN ('시급', '일급', '주급', '월급', '건당', '협의') THEN
    RAISE EXCEPTION '급여 형태가 올바르지 않습니다.';
  END IF;

  IF p_job_wage_amount IS NOT NULL AND p_job_wage_amount < 0 THEN
    RAISE EXCEPTION '급여 금액은 0 이상이어야 합니다.';
  END IF;

  IF p_job_is_always_recruiting = TRUE AND p_job_recruitment_deadline IS NOT NULL THEN
    RAISE EXCEPTION '상시 모집은 마감일과 함께 사용할 수 없습니다.';
  END IF;

  IF p_job_is_always_recruiting = FALSE AND p_job_recruitment_deadline IS NULL THEN
    RAISE EXCEPTION '모집 마감일 또는 상시 모집을 선택해주세요.';
  END IF;

  IF p_images IS NULL OR JSONB_TYPEOF(p_images) <> 'array'
    OR JSONB_ARRAY_LENGTH(p_images) > 10 THEN
    RAISE EXCEPTION '이미지 목록이 올바르지 않습니다.';
  END IF;

  INSERT INTO public.posts (
    author_id,
    upper_region,
    lower_region,
    category,
    title,
    content,
    place_name,
    place_latitude,
    place_longitude,
    place_address,
    place_road_address,
    place_category,
    job_wage_type,
    job_wage_amount,
    job_working_time,
    job_recruitment_deadline,
    job_is_always_recruiting
  )
  VALUES (
    v_account_id,
    BTRIM(p_upper_region),
    BTRIM(p_lower_region),
    'job',
    BTRIM(p_title),
    BTRIM(p_content),
    NULLIF(BTRIM(p_place_name), ''),
    p_place_latitude,
    p_place_longitude,
    NULLIF(BTRIM(p_place_address), ''),
    NULLIF(BTRIM(p_place_road_address), ''),
    NULLIF(BTRIM(p_place_category), ''),
    NULLIF(BTRIM(p_job_wage_type), ''),
    p_job_wage_amount,
    NULLIF(BTRIM(p_job_working_time), ''),
    p_job_recruitment_deadline,
    COALESCE(p_job_is_always_recruiting, FALSE)
  )
  RETURNING id INTO v_post_id;

  FOR v_image IN SELECT value FROM JSONB_ARRAY_ELEMENTS(p_images)
  LOOP
    IF JSONB_TYPEOF(v_image) <> 'object'
      OR NULLIF(BTRIM(v_image ->> 'storage_path'), '') IS NULL
      OR NULLIF(BTRIM(v_image ->> 'public_url'), '') IS NULL
      OR (v_image ->> 'sort_order')::INTEGER < 0
      OR SPLIT_PART(v_image ->> 'storage_path', '/', 1) <> 'accounts'
      OR SPLIT_PART(v_image ->> 'storage_path', '/', 2) <> v_account_id::TEXT THEN
      RAISE EXCEPTION '이미지 정보가 올바르지 않습니다.';
    END IF;

    INSERT INTO public.post_images (
      post_id, storage_path, public_url, sort_order
    )
    VALUES (
      v_post_id,
      BTRIM(v_image ->> 'storage_path'),
      BTRIM(v_image ->> 'public_url'),
      (v_image ->> 'sort_order')::INTEGER
    );
  END LOOP;

  RETURN v_post_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_job_post_with_images(
  p_post_id UUID,
  p_upper_region TEXT,
  p_lower_region TEXT,
  p_title TEXT,
  p_content TEXT,
  p_images JSONB DEFAULT '[]'::JSONB,
  p_place_name TEXT DEFAULT NULL,
  p_place_latitude DOUBLE PRECISION DEFAULT NULL,
  p_place_longitude DOUBLE PRECISION DEFAULT NULL,
  p_place_address TEXT DEFAULT NULL,
  p_place_road_address TEXT DEFAULT NULL,
  p_place_category TEXT DEFAULT NULL,
  p_job_wage_type TEXT DEFAULT NULL,
  p_job_wage_amount NUMERIC DEFAULT NULL,
  p_job_working_time TEXT DEFAULT NULL,
  p_job_recruitment_deadline DATE DEFAULT NULL,
  p_job_is_always_recruiting BOOLEAN DEFAULT FALSE
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_account_id UUID := public.current_account_id();
  v_post_id UUID;
  v_image JSONB;
  v_removed_storage_paths TEXT[];
BEGIN
  IF v_account_id IS NULL THEN
    RAISE EXCEPTION 'Authenticated account is required';
  END IF;

  IF p_images IS NULL OR JSONB_TYPEOF(p_images) <> 'array'
    OR JSONB_ARRAY_LENGTH(p_images) > 10 THEN
    RAISE EXCEPTION '이미지 목록이 올바르지 않습니다.';
  END IF;

  SELECT id INTO v_post_id
  FROM public.posts
  WHERE id = p_post_id AND author_id = v_account_id AND category = 'job'
  FOR UPDATE;

  IF v_post_id IS NULL THEN
    RAISE EXCEPTION '일자리 게시글을 수정할 권한이 없습니다.';
  END IF;

  IF NULLIF(BTRIM(p_upper_region), '') IS NULL
    OR NULLIF(BTRIM(p_lower_region), '') IS NULL
    OR NULLIF(BTRIM(p_title), '') IS NULL
    OR NULLIF(BTRIM(p_content), '') IS NULL THEN
    RAISE EXCEPTION '게시 지역, 제목, 내용을 입력해주세요.';
  END IF;

  IF CHAR_LENGTH(BTRIM(p_title)) > 50 OR CHAR_LENGTH(BTRIM(p_content)) > 10000 THEN
    RAISE EXCEPTION '제목은 50자, 본문은 10,000자 이내로 입력해주세요.';
  END IF;

  IF p_job_wage_type IS NOT NULL
    AND p_job_wage_type NOT IN ('시급', '일급', '주급', '월급', '건당', '협의') THEN
    RAISE EXCEPTION '급여 형태가 올바르지 않습니다.';
  END IF;

  IF p_job_wage_amount IS NOT NULL AND p_job_wage_amount < 0 THEN
    RAISE EXCEPTION '급여 금액은 0 이상이어야 합니다.';
  END IF;

  IF p_job_is_always_recruiting = TRUE AND p_job_recruitment_deadline IS NOT NULL THEN
    RAISE EXCEPTION '상시 모집은 마감일과 함께 사용할 수 없습니다.';
  END IF;

  IF p_job_is_always_recruiting = FALSE AND p_job_recruitment_deadline IS NULL THEN
    RAISE EXCEPTION '모집 마감일 또는 상시 모집을 선택해주세요.';
  END IF;

  FOR v_image IN SELECT value FROM JSONB_ARRAY_ELEMENTS(p_images)
  LOOP
    IF JSONB_TYPEOF(v_image) <> 'object'
      OR NULLIF(BTRIM(v_image ->> 'storage_path'), '') IS NULL
      OR NULLIF(BTRIM(v_image ->> 'public_url'), '') IS NULL
      OR (v_image ->> 'sort_order') IS NULL
      OR (v_image ->> 'sort_order')::INTEGER < 0
      OR SPLIT_PART(v_image ->> 'storage_path', '/', 1) <> 'accounts'
      OR SPLIT_PART(v_image ->> 'storage_path', '/', 2) <> v_account_id::TEXT THEN
      RAISE EXCEPTION '이미지 정보가 올바르지 않습니다.';
    END IF;
  END LOOP;

  SELECT COALESCE(
    ARRAY_AGG(pi.storage_path ORDER BY pi.sort_order),
    ARRAY[]::TEXT[]
  )
  INTO v_removed_storage_paths
  FROM public.post_images pi
  WHERE pi.post_id = v_post_id
    AND NOT EXISTS (
      SELECT 1
      FROM JSONB_ARRAY_ELEMENTS(p_images) image
      WHERE image ->> 'storage_path' = pi.storage_path
    );

  IF COALESCE(ARRAY_LENGTH(v_removed_storage_paths, 1), 0) > 0 THEN
    INSERT INTO public.storage_cleanup_queue (
      account_id, bucket_id, storage_path, next_retry_at
    )
    SELECT v_account_id, 'community-images', storage_path, now()
    FROM UNNEST(v_removed_storage_paths) AS paths(storage_path)
    ON CONFLICT (account_id, bucket_id, storage_path) DO UPDATE
      SET attempt_count = 0,
          last_error = NULL,
          next_retry_at = now(),
          lease_until = NULL;
  END IF;

  UPDATE public.posts
  SET upper_region = BTRIM(p_upper_region),
      lower_region = BTRIM(p_lower_region),
      title = BTRIM(p_title),
      content = BTRIM(p_content),
      place_name = NULLIF(BTRIM(p_place_name), ''),
      place_latitude = p_place_latitude,
      place_longitude = p_place_longitude,
      place_address = NULLIF(BTRIM(p_place_address), ''),
      place_road_address = NULLIF(BTRIM(p_place_road_address), ''),
      place_category = NULLIF(BTRIM(p_place_category), ''),
      job_wage_type = NULLIF(BTRIM(p_job_wage_type), ''),
      job_wage_amount = p_job_wage_amount,
      job_working_time = NULLIF(BTRIM(p_job_working_time), ''),
      job_recruitment_deadline = p_job_recruitment_deadline,
      job_is_always_recruiting = COALESCE(p_job_is_always_recruiting, FALSE),
      updated_at = now()
  WHERE id = v_post_id;

  DELETE FROM public.post_images WHERE post_id = v_post_id;

  INSERT INTO public.post_images (
    post_id, storage_path, public_url, sort_order
  )
  SELECT
    v_post_id,
    BTRIM(image ->> 'storage_path'),
    BTRIM(image ->> 'public_url'),
    (image ->> 'sort_order')::INTEGER
  FROM JSONB_ARRAY_ELEMENTS(p_images) AS images(image);

  RETURN JSONB_BUILD_OBJECT(
    'post_id', v_post_id,
    'removed_storage_paths', TO_JSONB(v_removed_storage_paths)
  );
END;
$$;

